-- Mobile Blood Donation Management System (MBDMS)
-- Supabase / PostgreSQL
-- Revised seven-table database structure

-- 1. STAFF PROFILES
-- The ID is the same UUID used by Supabase Authentication.
CREATE TABLE IF NOT EXISTS public.staff_profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name TEXT NOT NULL,
    role TEXT NOT NULL CHECK (
        role IN (
            'administrator',
            'coordinator',
            'registration_staff',
            'medical_personnel',
            'donation_staff'
        )
    ),
    account_status TEXT NOT NULL DEFAULT 'active'
        CHECK (account_status IN ('active', 'inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. DONORS
CREATE TABLE IF NOT EXISTS public.donors (
    donor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name TEXT NOT NULL,
    middle_name TEXT,
    last_name TEXT NOT NULL,
    birthdate DATE NOT NULL,
    sex TEXT CHECK (sex IN ('male', 'female', 'other', 'prefer_not_to_say')),
    blood_type TEXT CHECK (
        blood_type IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')
    ),
    contact_number TEXT,
    address TEXT,
    consent_given BOOLEAN NOT NULL DEFAULT FALSE,
    consent_recorded_at TIMESTAMPTZ,
    donor_status TEXT NOT NULL DEFAULT 'active'
        CHECK (donor_status IN ('active', 'inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT donor_consent_timestamp_check CHECK (
        (consent_given = FALSE AND consent_recorded_at IS NULL)
        OR
        (consent_given = TRUE AND consent_recorded_at IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS donors_name_birthdate_idx
ON public.donors (last_name, first_name, birthdate);

-- 3. MBD ACTIVITIES
CREATE TABLE IF NOT EXISTS public.mbd_activities (
    activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_name TEXT NOT NULL,
    location TEXT NOT NULL,
    activity_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    activity_status TEXT NOT NULL DEFAULT 'planned'
        CHECK (
            activity_status IN ('planned', 'ongoing', 'completed', 'cancelled')
        ),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT activity_time_check CHECK (end_time > start_time),
    CONSTRAINT activity_name_date_unique UNIQUE (activity_date, activity_name)
);

-- 4. STAFF ASSIGNED TO ACTIVITIES
CREATE TABLE IF NOT EXISTS public.activity_staff_assignments (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL
        REFERENCES public.mbd_activities(activity_id) ON DELETE CASCADE,
    staff_id UUID NOT NULL
        REFERENCES public.staff_profiles(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT activity_staff_unique UNIQUE (activity_id, staff_id)
);

-- 5. DONOR PARTICIPATION IN ACTIVITIES
CREATE TABLE IF NOT EXISTS public.activity_donors (
    participation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL
        REFERENCES public.mbd_activities(activity_id) ON DELETE CASCADE,
    donor_id BIGINT NOT NULL
        REFERENCES public.donors(donor_id) ON DELETE RESTRICT,
    participation_status TEXT NOT NULL DEFAULT 'registered'
        CHECK (
            participation_status IN (
                'registered', 'attended', 'withdrawn', 'no_show'
            )
        ),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT activity_donor_unique UNIQUE (activity_id, donor_id)
);

-- 6. SCREENING RECORDS
CREATE TABLE IF NOT EXISTS public.screening_records (
    screening_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participation_id BIGINT NOT NULL UNIQUE
        REFERENCES public.activity_donors(participation_id) ON DELETE RESTRICT,
    systolic_bp INTEGER,
    diastolic_bp INTEGER,
    weight_kg NUMERIC(5,2),
    hemoglobin_g_dl NUMERIC(4,2),
    screening_outcome TEXT NOT NULL
        CHECK (screening_outcome IN ('accepted', 'deferred', 'rejected')),
    outcome_reason TEXT,
    notes TEXT,
    screened_by UUID NOT NULL
        REFERENCES public.staff_profiles(id) ON DELETE RESTRICT,
    screened_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT screening_systolic_check
        CHECK (systolic_bp IS NULL OR systolic_bp BETWEEN 50 AND 300),
    CONSTRAINT screening_diastolic_check
        CHECK (diastolic_bp IS NULL OR diastolic_bp BETWEEN 30 AND 200),
    CONSTRAINT screening_bp_order_check
        CHECK (
            systolic_bp IS NULL OR diastolic_bp IS NULL
            OR diastolic_bp < systolic_bp
        ),
    CONSTRAINT screening_weight_check
        CHECK (weight_kg IS NULL OR weight_kg BETWEEN 1 AND 500),
    CONSTRAINT screening_hemoglobin_check
        CHECK (hemoglobin_g_dl IS NULL OR hemoglobin_g_dl BETWEEN 1 AND 30),
    CONSTRAINT deferred_reason_required
        CHECK (
            screening_outcome <> 'deferred'
            OR NULLIF(TRIM(outcome_reason), '') IS NOT NULL
        ),
    CONSTRAINT accepted_reason_empty
        CHECK (
            screening_outcome <> 'accepted'
            OR NULLIF(TRIM(outcome_reason), '') IS NULL
        )
);

-- 7. DONATION RECORDS
CREATE TABLE IF NOT EXISTS public.donation_records (
    donation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participation_id BIGINT NOT NULL UNIQUE
        REFERENCES public.activity_donors(participation_id) ON DELETE RESTRICT,
    bag_serial_no TEXT NOT NULL UNIQUE,
    volume_ml INTEGER,
    donation_status TEXT NOT NULL
        CHECK (donation_status IN ('completed', 'not_completed')),
    recorded_by UUID NOT NULL
        REFERENCES public.staff_profiles(id) ON DELETE RESTRICT,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT donation_volume_check
        CHECK (volume_ml IS NULL OR volume_ml BETWEEN 0 AND 1000),
    CONSTRAINT completed_donation_volume_required
        CHECK (
            donation_status <> 'completed'
            OR (volume_ml IS NOT NULL AND volume_ml > 0)
        )
);

-- Helpful indexes for related-record searches
CREATE INDEX IF NOT EXISTS assignments_staff_idx
ON public.activity_staff_assignments (staff_id);

CREATE INDEX IF NOT EXISTS activity_donors_donor_idx
ON public.activity_donors (donor_id);

CREATE INDEX IF NOT EXISTS screening_screened_by_idx
ON public.screening_records (screened_by);

CREATE INDEX IF NOT EXISTS donations_recorded_by_idx
ON public.donation_records (recorded_by);

